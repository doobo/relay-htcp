#!/bin/sh
# Collect the licenses of every module in the build list into a single file so
# release archives ship the notices required by Apache-2.0 section 4(d).
#
# POSIX sh on purpose: the Makefile runs this with `sh`, which works on Linux
# (dash/bash) and on Windows (msys2/Git sh) without requiring bash.
#
# Usage: scripts/third-party-licenses.sh [dist-dir] [version]
set -eu

dist="${1:-dist}"
version="${2:-dev}"
root="$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)"
cd "$root"

GO_BIN="${GO:-go}"
if ! command -v "$GO_BIN" >/dev/null 2>&1; then
  echo "找不到 Go 可执行文件：$GO_BIN（可用 GO=/path/to/go 指定）" >&2
  exit 1
fi

mkdir -p "$dist"
out="$dist/THIRD_PARTY_LICENSES"
list="$(mktemp)"
trap 'rm -f "$list"' EXIT

"$GO_BIN" mod download
"$GO_BIN" list -m -f '{{if not .Main}}{{.Path}} {{.Dir}}{{end}}' all >"$list"

{
  printf 'relay-htcp %s third-party licenses\n' "$version"
  printf '===============================================================\n'
  printf 'Generated by scripts/third-party-licenses.sh - do not edit by hand.\n'
  printf 'The project itself is licensed under Apache-2.0; see LICENSE.\n'
  printf 'Module versions are taken from go.mod / go.sum.\n'

  while read -r module dir; do
    [ -n "$module" ] || continue
    printf '\n----------------------------------------------------------------\n'
    printf '%s\n' "$module"

    if [ -z "$dir" ] || [ ! -d "$dir" ]; then
      printf 'License: module source not found in the module cache\n'
      continue
    fi

    files=""
    first=""
    for f in "$dir"/LICENSE* "$dir"/LICENCE* "$dir"/COPYING* "$dir"/NOTICE*; do
      [ -f "$f" ] || continue
      files="$files $f"
      [ -n "$first" ] || first="$f"
    done

    if [ -z "$first" ]; then
      printf 'License: no LICENSE/NOTICE file found in the module\n'
      continue
    fi

    label="upstream"
    if grep -qi 'Apache License' "$first"; then
      label="Apache-2.0"
    elif grep -q 'Permission is hereby granted, free of charge' "$first"; then
      label="MIT"
    elif grep -q 'Redistribution and use in source and binary forms' "$first"; then
      label="BSD-3-Clause"
    fi
    printf 'License: %s\n' "$label"
    printf '%s\n' '----------------------------------------------------------------'

    for f in $files; do
      printf '[%s]\n' "$(basename "$f")"
      cat "$f"
      printf '\n'
    done
  done <"$list"
} >"$out"

cp LICENSE "$dist/LICENSE"
echo "已生成 $out 与 $dist/LICENSE"
